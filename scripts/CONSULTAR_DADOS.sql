EXPLAIN QUERY PLAN
SELECT
    e.NOME_ESTOQUE,
    SUM(p.PRECO * p.QUANTIDADE_ESTOQUE) AS FORTUNA_PARADA,
    SUM(p.QUANTIDADE_ESTOQUE) AS TOTAL_ITENS
FROM ESTOQUE e
JOIN LOCALIZACAO_PLATELEIRAS lp ON e.ID_ESTOQUE = lp.ID_ESTOQUE
JOIN PLATELEIRAS pr ON lp.ID_LOCALIZACAO_PLATELEIRA = pr.ID_LOCALIZACAO_PLATELEIRA
JOIN PECAS p ON pr.ID_PLATELEIRAS = p.ID_PLATELEIRAS
GROUP BY e.ID_ESTOQUE, e.NOME_ESTOQUE;

SELECT
    e.NOME_ESTOQUE,
    SUM(p.PRECO * p.QUANTIDADE_ESTOQUE) AS FORTUNA_PARADA,
    SUM(p.QUANTIDADE_ESTOQUE) AS TOTAL_ITENS
FROM ESTOQUE e
JOIN LOCALIZACAO_PLATELEIRAS lp ON e.ID_ESTOQUE = lp.ID_ESTOQUE
JOIN PLATELEIRAS pr ON lp.ID_LOCALIZACAO_PLATELEIRA = pr.ID_LOCALIZACAO_PLATELEIRA
JOIN PECAS p ON pr.ID_PLATELEIRAS = p.ID_PLATELEIRAS
