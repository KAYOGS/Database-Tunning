SELECT p.ID_PLATELEIRAS, pr.NOME_PLATELEIRA, COUNT(*) AS TOTAL_PECAS, AVG(p.PRECO) AS PRECO_MEDIO
FROM PECAS p
JOIN PLATELEIRAS pr ON p.ID_PLATELEIRAS = pr.ID_PLATELEIRAS
GROUP BY p.ID_PLATELEIRAS, pr.NOME_PLATELEIRA;

